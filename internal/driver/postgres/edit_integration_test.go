var (
	edOnce sync.Once
	edErr  error
)

func openEd(t *testing.T, readOnly bool) driver.Conn {
	t.Helper()
	cfg, pw := itConfig(t)
	edOnce.Do(func() {
		admin := itConn(t, "")
		for _, q := range []string{"DROP DATABASE IF EXISTS " + edDB + " WITH (FORCE)", "CREATE DATABASE " + edDB} {
			if _, edErr = admin.Exec(context.Background(), q); edErr != nil {
				return
			}
		}
		_, edErr = itConn(t, edDB).Exec(context.Background(), edFixture, pgx.QueryExecModeSimpleProtocol)
	})
	if edErr != nil {
		t.Fatalf("ed fixture: %v", edErr)
	}
	cfg.ReadOnly = readOnly
	c, err := New().Open(context.Background(), cfg, pw)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { c.Close() })
	return c
}

// itConn connects straight to db (the DSN's database when empty), bypassing
// the driver.
func itConn(t *testing.T, db string) *pgx.Conn {
	t.Helper()
	cfg, err := pgx.ParseConfig(os.Getenv("QUARRY_TEST_PG_DSN"))
	if err != nil {
		t.Fatal(err)
	}
	if db != "" {
		cfg.Database = db
	}
	pc, err := pgx.ConnectConfig(context.Background(), cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { pc.Close(context.Background()) })
	return pc
}

func edNode(folder, name string) *driver.Node {
	return &driver.Node{Path: []string{edDB, "ed", folder, name}}
}

func TestITDataQuery(t *testing.T) {
	c := openEd(t, false)
	dv := c.(driver.DataViewer)
	s := newSession(t, c, driver.Scope{Database: edDB})
	run := func(filter string, orderBy ...string) [][]any {
		t.Helper()
		q, err := dv.DataQuery(edNode(folderTables, "MixedCase"), filter, orderBy)
		if err != nil {
			t.Fatal(err)
		}
		_, rows := all(t, s, q)
		return rows
	}
	ids := func(rows [][]any) []int64 {
		var out []int64
		for _, r := range rows {
			out = append(out, r[0].(int64))
		}
		return out
	}
	if got := ids(run("")); len(got) != 4 {
		t.Errorf("all rows: %v", got)
	}
	if got := ids(run("", "n DESC")); !slices.Equal(got, []int64{4, 1, 3, 2}) { // NULLS FIRST on DESC
		t.Errorf("n DESC: %v", got)
	}
	if got := ids(run(`"Label" IS NOT NULL AND n > 5 -- trailing comment`, "Label")); !slices.Equal(got, []int64{1, 3, 2}) {
		t.Errorf("filtered by Label: %v", got)
	}
	if got := ids(run("WHERE n < 25;", "Id desc")); !slices.Equal(got, []int64{3, 2}) {
		t.Errorf("WHERE prefix: %v", got)
	}
	for _, bad := range []string{`Id; DROP TABLE ed.nokey --`, "Id DESC NULLS LAST", `"Id" DESC, "n"`} {
		if q, err := dv.DataQuery(edNode(folderTables, "MixedCase"), "", []string{bad}); err == nil {
			t.Errorf("orderBy %q accepted: %s", bad, q)
		}
	}
	// A name that is not a column fails on the server, harmlessly.
	q, err := dv.DataQuery(edNode(folderTables, "MixedCase"), "", []string{"id;drop"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := s.Execute(context.Background(), driver.Statement{Text: q}); err == nil {
		t.Errorf("%s: expected an error", q)
	}
	for _, n := range []*driver.Node{edNode(folderViews, "cheap"), edNode(folderMatviews, "stock")} {
		q, err := dv.DataQuery(n, "", nil)
		if err != nil {
			t.Fatal(err)
		}
		if n.Path[2] == folderMatviews {
			continue // not populated
		}
		all(t, s, q)
	}
	if _, err := dv.DataQuery(&driver.Node{Path: []string{edDB, "ed", folderFunctions, "f()"}}, "", nil); err == nil {
		t.Error("function accepted")
	}
}

func TestITDescribe(t *testing.T) {
	c := openEd(t, false)
	d := c.(driver.Describer)
	ctx := context.Background()

	items, err := d.Describe(ctx, edNode(folderTables, "items"))
	if err != nil {
		t.Fatal(err)
	}
	col := func(od *driver.ObjectDetails, name string) driver.ColumnInfo {
		for _, c := range od.Columns {
			if c.Name == name {
				return c
			}
		}
		t.Fatalf("no column %s in %+v", name, od.Columns)
		return driver.ColumnInfo{}
	}
	for _, want := range []driver.ColumnInfo{
		{Name: "id", Type: "integer", Default: "GENERATED ALWAYS AS IDENTITY", PrimaryKey: true},
		{Name: "sku", Type: "character varying(20)", Comment: "Stock keeping unit, it's unique"},
		{Name: "qty", Type: "integer", Default: "1"},
		{Name: "price", Type: "numeric(10,2)", Nullable: true},
		{Name: "total", Type: "numeric", Default: "GENERATED ALWAYS AS (((qty)::numeric * price)) STORED", Nullable: true},
		{Name: "mood", Type: "shop.mood", Nullable: true},
	} {
		if got := col(items, want.Name); got != want {
			t.Errorf("column %s:\n got %+v\nwant %+v", want.Name, got, want)
		}
	}
	names := func(rows []driver.DetailRow) []string {
		var out []string
		for _, r := range rows {
			out = append(out, r.Name)
		}
		return out
	}
	if got := names(items.Indexes); !slices.Equal(got, []string{"items_pkey", "items_name_idx", "items_sku_key"}) {
		t.Errorf("indexes: %q", got)
	}
	if items.Indexes[1].Definition != "CREATE INDEX items_name_idx ON ed.items USING btree (lower(name)) WHERE (qty > 0)" {
		t.Errorf("index def: %q", items.Indexes[1].Definition)
	}
	if got := names(items.Constraints); !slices.Equal(got, []string{"items_pkey", "items_sku_key", "items_parent_fkey", "items_qty_check"}) {
		t.Errorf("constraints: %q", got)
	}
	if def := items.Constraints[2].Definition; def != "FOREIGN KEY (parent) REFERENCES ed.items(id) ON DELETE SET NULL" {
		t.Errorf("fk: %q", def)
	}
	if len(items.Triggers) != 1 || items.Triggers[0].Name != "items_touch" ||
		!strings.Contains(items.Triggers[0].Definition, "BEFORE UPDATE ON ed.items FOR EACH ROW EXECUTE FUNCTION touch()") {
		t.Errorf("triggers: %+v", items.Triggers)
	}
	stats := map[string]string{}
	for _, r := range items.Stats {
		stats[r.Name] = r.Definition
	}
	if stats["Estimated rows"] != "2" || !strings.HasSuffix(stats["Total size"], "kB") || stats["Last analyze"] == "never" ||
		stats["Last vacuum"] != "never" || stats["Seq scans"] == "n/a" {
		t.Errorf("stats: %+v", stats)
	}
	for _, frag := range []string{
		"CREATE TABLE ed.items (\n    id integer GENERATED ALWAYS AS IDENTITY NOT NULL,\n    sku character varying(20) NOT NULL,\n",
		"    name text COLLATE pg_catalog.\"C\",\n",
		"    CONSTRAINT items_pkey PRIMARY KEY (id),\n",
		"CREATE INDEX items_name_idx ON ed.items USING btree (lower(name)) WHERE (qty > 0);",
		"COMMENT ON COLUMN ed.items.sku IS 'Stock keeping unit, it''s unique';",
		"COMMENT ON CONSTRAINT items_qty_check ON ed.items IS 'no negative stock';",
		"COMMENT ON TRIGGER items_touch ON ed.items IS 'bump';",
	} {
		if !strings.Contains(items.DDL, frag) {
			t.Errorf("DDL lacks %q:\n%s", frag, items.DDL)
		}
	}
	t.Logf("items DDL:\n%s", items.DDL)

	part, err := d.Describe(ctx, edNode(folderTables, "measurements"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(part.DDL, "\nPARTITION BY RANGE (logdate);") || !strings.Contains(part.DDL, "CREATE INDEX measurements_v_idx") {
		t.Errorf("partitioned DDL:\n%s", part.DDL)
	}
	if part.Stats[0].Definition == "n/a" || strings.HasPrefix(part.Stats[1].Definition, "0") {
		t.Errorf("partitioned stats: %+v", part.Stats)
	}

	view, err := d.Describe(ctx, edNode(folderViews, "cheap"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(view.DDL, "CREATE VIEW ed.cheap WITH (check_option=local) AS\nSELECT id,\n") ||
		!strings.Contains(view.DDL, "COMMENT ON COLUMN ed.cheap.sku IS 'view column';") || view.Stats != nil || len(view.Columns) != 2 {
		t.Errorf("view: %+v\n%s", view, view.DDL)
	}
	mv, err := d.Describe(ctx, edNode(folderMatviews, "stock"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(mv.DDL, "CREATE MATERIALIZED VIEW ed.stock AS\nSELECT sku,") || !strings.Contains(mv.DDL, "WITH NO DATA;") ||
		!strings.Contains(mv.DDL, "CREATE UNIQUE INDEX stock_sku ON ed.stock USING btree (sku);") || len(mv.Stats) == 0 {
		t.Errorf("matview:\n%s", mv.DDL)
	}
	mixed, err := d.Describe(ctx, edNode(folderTables, "MixedCase"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(mixed.DDL, "CREATE TABLE ed.\"MixedCase\" (\n    \"Id\" integer NOT NULL,") {
		t.Errorf("mixed-case DDL:\n%s", mixed.DDL)
	}

	if _, err := d.Describe(ctx, edNode(folderTables, "nope")); err == nil || !strings.Contains(err.Error(), "does not exist") {
		t.Errorf("missing table: %v", err)
	}
	if _, err := d.Describe(ctx, &driver.Node{Path: []string{edDB, "ed", folderSequences, "s"}}); err == nil {
		t.Error("sequence accepted")
	}
}

// TestITDDLRoundTrip recreates every ed relation from its DDL in a fresh
// schema of the same name (the original renamed away, all in a rolled back
// transaction) and checks the recreated relations describe identically.
func TestITDDLRoundTrip(t *testing.T) {
	openEd(t, false)
	pc := itConn(t, edDB)
	ctx := context.Background()
	tx, err := pc.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback(ctx)
	rels := []string{"items", "cheap", "stock", "measurements", "measurements_2024", "MixedCase", "nopk_uq", "nokey", "composite"}
	orig := map[string]*driver.ObjectDetails{}
	for _, r := range rels {
		d, err := describeRel(ctx, tx, "ed", r)
		if err != nil {
			t.Fatalf("%s: %v", r, err)
		}
		orig[r] = d
	}
	if _, err := tx.Exec(ctx, "ALTER SCHEMA ed RENAME TO ed_orig; CREATE SCHEMA ed", pgx.QueryExecModeSimpleProtocol); err != nil {
		t.Fatal(err)
	}
	for _, r := range rels {
		if _, err := tx.Exec(ctx, orig[r].DDL, pgx.QueryExecModeSimpleProtocol); err != nil {
			t.Fatalf("%s: %v\n%s", r, err, orig[r].DDL)
		}
	}
	for _, r := range rels {
		got, err := describeRel(ctx, tx, "ed", r)
		if err != nil {
			t.Fatal(err)
		}
		want := orig[r]
		if got.DDL != want.DDL {
			t.Errorf("%s DDL differs:\n got %s\nwant %s", r, got.DDL, want.DDL)
		}
		for _, f := range []struct {
			name      string
			got, want any
		}{
			{"columns", got.Columns, want.Columns},
			{"indexes", got.Indexes, want.Indexes},
			{"constraints", got.Constraints, want.Constraints},
			{"triggers", got.Triggers, want.Triggers},
		} {
			if !reflect.DeepEqual(f.got, f.want) {
				t.Errorf("%s %s differ:\n got %+v\nwant %+v", r, f.name, f.got, f.want)
			}
		}
	}
}

