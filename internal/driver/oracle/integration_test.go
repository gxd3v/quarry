func TestITTypes(t *testing.T) {
	c := open(t)
	s := newSession(t, c, driver.Scope{Schema: itUser})
	q := `select 1 a, 1.5 b, cast(12.5 as number(10,2)) c, cast(3 as number(5)) d, to_binary_float(1.25) e,
	to_binary_double(2.5) f, 'txt' g, cast('c' as char(3)) h, cast('v' as varchar2(10)) i, n'nç' j,
	to_clob('clob') k, interval '1-2' year to month l, interval '1 02:03:04.5' day to second m,
	date '2024-01-02' n, timestamp '2024-01-02 03:04:05.123' o, timestamp '2024-01-02 03:04:05 +02:00' p,
	hextoraw('00ff') q, to_blob(hextoraw('0102')) r, 123456789012345678901234567890 s, cast(null as number) t,
	json('{"b": [1, 2], "a": "x"}') u, true v, -0.5 w, count(*) over () x, cast(2.5 as float) y, to_binary_float(0.1) z
	from dual`
	r, rows := all(t, s, q)
	if r.Affected() != -1 {
		t.Errorf("Affected = %d", r.Affected())
	}
	want := []any{
		int64(1), driver.Number("1.5"), driver.Number("12.5"), int64(3), 1.25,
		2.5, "txt", "c  ", "v", "nç",
		"clob", "+01-02", "+01 02:03:04.500000",
		time.Date(2024, 1, 2, 0, 0, 0, 0, time.UTC), time.Date(2024, 1, 2, 3, 4, 5, 123000000, time.UTC),
		time.Date(2024, 1, 2, 1, 4, 5, 0, time.UTC),
		[]byte{0, 255}, []byte{1, 2}, driver.Number("123456789012345678901234567890"), nil,
		driver.JSON(`{"b":[1,2],"a":"x"}`), int64(1), // go-ora reads BOOLEAN as NUMBER
		driver.Number("-0.5"), int64(1), driver.Number("2.5"), 0.1,
	}
	got := rows[0]
	if len(got) != len(want) {
		t.Fatalf("got %d values, want %d", len(got), len(want))
	}
	for i := range want {
		if tm, ok := got[i].(time.Time); ok {
			if w, ok := want[i].(time.Time); ok && tm.Equal(w) {
				continue
			}
		}
		if !reflect.DeepEqual(got[i], want[i]) {
			t.Errorf("col %s (%s): got %#v, want %#v", r.Columns()[i].Name, r.Columns()[i].Type, got[i], want[i])
		}
	}
	var types []string
	for _, col := range r.Columns() {
		types = append(types, col.Type)
	}
	t.Logf("types: %q", types)
	wantTypes := map[int]string{0: "NUMBER", 2: "NUMBER(10,2)", 3: "NUMBER(5)", 4: "BINARY_FLOAT", 5: "BINARY_DOUBLE",
		7: "CHAR(3)", 8: "VARCHAR2(10)", 10: "CLOB", 11: "INTERVAL YEAR TO MONTH", 12: "INTERVAL DAY TO SECOND",
		13: "DATE", 14: "TIMESTAMP", 15: "TIMESTAMP WITH TIME ZONE", 16: "RAW", 17: "BLOB", 20: "JSON"}
	for i, w := range wantTypes {
		if types[i] != w {
			t.Errorf("col %d type %q, want %q", i, types[i], w)
		}
	}
	if r.Columns()[0].Name != "A" {
		t.Errorf("column name %q", r.Columns()[0].Name)
	}

	// Table columns: ROWID, LTZ, NVARCHAR2, JSON and BOOLEAN columns.
	_, rows = all(t, s, "select rowid, flag, data from items where sku = 'A-1'")
	if id, ok := rows[0][0].(string); !ok || len(id) != 18 {
		t.Errorf("rowid: %#v", rows[0][0])
	}
	if rows[0][1] != nil || rows[0][2] != nil {
		t.Errorf("nulls: %#v", rows[0])
	}
}

// withRaw runs fn on a direct admin connection.
func withRaw(t *testing.T, fn func(l *link)) {
	t.Helper()
	cfg, pw := itConfig(t)
	l, err := rawConn(cfg, pw)
	if err != nil {
		t.Fatal(err)
	}
	defer l.close()
	fn(l)
}
